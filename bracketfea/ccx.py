"""Write CalculiX input decks, run ccx, and parse .frd / .dat results."""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np

G = 9810.0  # mm/s^2  (units: mm, N, MPa, tonne, s)

_CANDIDATES = [
    os.environ.get("CCX_PATH", ""),
    "/Applications/FreeCAD.app/Contents/Resources/bin/ccx",
    shutil.which("ccx") or "",
]


def ccx_path() -> str:
    for c in _CANDIDATES:
        if c and Path(c).exists():
            return c
    raise FileNotFoundError("CalculiX (ccx) not found; set CCX_PATH")


def run_ccx(workdir: str | Path, job: str, threads: int = 1, timeout: float = 3600) -> str:
    env = dict(os.environ, OMP_NUM_THREADS=str(threads), CCX_NPROC_EQUATION_SOLVER=str(threads))
    res = subprocess.run([ccx_path(), "-i", job], cwd=workdir, env=env, capture_output=True,
                         text=True, timeout=timeout)
    log = res.stdout + res.stderr
    Path(workdir, f"{job}.log").write_text(log)
    if res.returncode != 0 or "*ERROR" in log:
        err = [l for l in log.splitlines() if "ERROR" in l]
        raise RuntimeError(f"ccx failed for {job}: {err[:5]}")
    return log


# ----------------------------------------------------------------------------- input deck

@dataclass
class Material:
    name: str = "STEEL"
    E: float = 207000.0      # MPa
    nu: float = 0.292
    rho: float = 7.85e-9     # tonne/mm^3


def _fmt_ids(ids, per_line: int = 16) -> str:
    ids = list(ids)
    return "\n".join(", ".join(str(i) for i in ids[k:k + per_line]) for k in range(0, len(ids), per_line))


def write_mesh(f, nodes: np.ndarray, tets: np.ndarray, sets: dict, extra_nodes: dict | None = None):
    f.write("*NODE\n")
    for i, (x, y, z) in enumerate(nodes, start=1):
        f.write(f"{i}, {x:.6f}, {y:.6f}, {z:.6f}\n")
    for nid, (x, y, z) in (extra_nodes or {}).items():
        f.write(f"{nid}, {x:.6f}, {y:.6f}, {z:.6f}\n")
    f.write("*ELEMENT, TYPE=C3D10, ELSET=Eall\n")
    for e, conn in enumerate(tets + 1, start=1):
        f.write(f"{e}, " + ", ".join(str(c) for c in conn) + "\n")
    for name, idx in sets.items():
        f.write(f"*NSET, NSET={name}\n{_fmt_ids(np.asarray(idx) + 1)}\n")


def write_material(f, mat: Material):
    f.write(f"*MATERIAL, NAME={mat.name}\n*ELASTIC\n{mat.E}, {mat.nu}\n*DENSITY\n{mat.rho:.6e}\n")
    f.write(f"*SOLID SECTION, ELSET=Eall, MATERIAL={mat.name}\n")


def write_bracket_deck(path: str | Path, mesh, mat: Material, comp_mass: float, comp_cg,
                       load_g, n_modes: int = 10, ssd: dict | None = None,
                       static: bool = True, frequency: bool = True):
    """Bracket model: bolt holes fixed, component = point mass rigidly tied to the mounting hole.

    comp_mass  component mass in tonne (kg * 1e-3)
    comp_cg    component centre of gravity (mm)
    load_g     quasi-static load factors (n_x, n_y, n_z) in g, applied to bracket and component
    ssd        optional steady-state dynamics step: dict(f_lo, f_hi, n, damping, direction)
    """
    n = mesh.n_nodes
    cg, rot = n + 1, n + 2
    with open(path, "w") as f:
        f.write("** L-bracket, generated by bracketfea\n")
        write_mesh(f, mesh.nodes, mesh.tets, {"FIX": mesh.sets["FIX"], "MOUNT": mesh.sets["MOUNT"]},
                   extra_nodes={cg: comp_cg, rot: comp_cg})
        f.write(f"*NSET, NSET=CG\n{cg}\n*ELSET, ELSET=EONE\n1\n")
        f.write(f"*ELEMENT, TYPE=MASS, ELSET=EMASS\n{len(mesh.tets) + 1}, {cg}\n")
        f.write(f"*MASS, ELSET=EMASS\n{comp_mass:.6e}\n")
        write_material(f, mat)
        f.write(f"*RIGID BODY, NSET=MOUNT, REF NODE={cg}, ROT NODE={rot}\n")
        f.write("*BOUNDARY\nFIX, 1, 3\n")

        if static:
            nx, ny, nz = load_g
            amag = float(np.linalg.norm(load_g))
            f.write("*STEP\n*STATIC\n")
            f.write("*CLOAD\n")
            for dof, nn in zip((1, 2, 3), load_g):
                f.write(f"CG, {dof}, {comp_mass * G * nn:.6e}\n")
            f.write(f"*DLOAD\nEall, GRAV, {amag * G:.6e}, {nx / amag:.6f}, {ny / amag:.6f}, {nz / amag:.6f}\n")
            f.write("*NODE FILE\nU\n*EL FILE\nS\n*NODE PRINT, NSET=CG\nU\n*END STEP\n")

        if frequency:
            f.write(f"*STEP\n*FREQUENCY, STORAGE={'YES' if ssd else 'NO'}\n{n_modes}\n")
            f.write("*NODE FILE\nU\n*EL FILE\nS\n*END STEP\n")

        if ssd:
            d = np.asarray(ssd.get("direction", (1.0, 0.0, 0.0)), dtype=float)
            d = d / np.linalg.norm(d)
            f.write(f"*STEP\n*STEADY STATE DYNAMICS, HARMONIC=YES\n")
            f.write(f"{ssd['f_lo']}, {ssd['f_hi']}, {ssd['n']}, 1.\n")
            f.write(f"*MODAL DAMPING\n1, {n_modes}, {ssd['damping']}\n")
            # base acceleration of 1 g = inertial body force on everything (relative coordinates);
            # GRAV acts on Eall only, so the point mass gets the same body force as a CLOAD
            f.write(f"*DLOAD\nEall, GRAV, {G:.6e}, {d[0]:.6f}, {d[1]:.6f}, {d[2]:.6f}\n")
            f.write("*CLOAD\n")
            for dof in range(3):
                if d[dof] != 0:
                    f.write(f"CG, {dof + 1}, {comp_mass * G * d[dof]:.6e}\n")
            # field output requests carry over between steps: restrict them to one node / element
            f.write("*NODE FILE, NSET=CG\nU\n*EL FILE, ELSET=EONE\nS\n*NODE PRINT, NSET=CG\nU\n*END STEP\n")
    return cg


# ----------------------------------------------------------------------------- results

@dataclass
class FrdBlock:
    name: str          # DISP, STRESS, ...
    value: float       # time / frequency of the result set
    step: int
    mode: int | None
    nodes: np.ndarray  # node ids (1-based)
    data: np.ndarray   # (n, ncomp)


def read_frd(path: str | Path, want=("DISP", "STRESS")) -> list[FrdBlock]:
    """Stream an ASCII .frd file and return the wanted nodal result blocks."""
    blocks: list[FrdBlock] = []
    mode, step, value = None, 0, 0.0
    name, rows, in_block = None, [], False
    with open(path) as f:
        for line in f:
            if in_block:
                if line.startswith(" -1"):
                    if name in want:
                        rows.append(line.rstrip("\n"))
                elif line.startswith(" -3"):
                    if name in want and rows:
                        blocks.append(_frd_block(name, value, step, mode, rows))
                    in_block, rows = False, []
                continue
            if line.startswith("    1PMODE"):
                mode = int(line.split()[-1])
            elif line.startswith("    1PSTEP"):
                parts = line.split()
                step = int(parts[-1]) if len(parts) > 2 else step
            elif line.startswith("  100C"):
                value = float(line[12:24])
                name = None
            elif line.startswith(" -4") and name is None:
                name = line.split()[1]
                in_block = True
    return blocks


def _frd_block(name, value, step, mode, rows) -> FrdBlock:
    ncomp = (len(rows[0]) - 13) // 12   # "ALL"-type components are not stored
    fixed = "".join(r[3:13 + 12 * ncomp].ljust(10 + 12 * ncomp) for r in rows)
    arr = np.frombuffer(fixed.encode(), dtype=f"S10,{','.join(['S12'] * ncomp)}")
    ids = arr["f0"].astype(np.int64)
    vals = np.stack([arr[f"f{k + 1}"].astype(np.float64) for k in range(ncomp)], axis=1)
    return FrdBlock(name, value, step, mode, ids, vals)


def frd_field(block: FrdBlock, n_nodes: int) -> np.ndarray:
    """Dense (n_nodes, ncomp) array for mesh nodes 1..n_nodes (extra nodes dropped)."""
    out = np.zeros((n_nodes, block.data.shape[1]))
    m = block.nodes <= n_nodes
    out[block.nodes[m] - 1] = block.data[m]
    return out


_FLOAT = r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?"


def read_dat_modes(path: str | Path) -> dict:
    """Eigenfrequencies, participation factors and effective modal masses from a .dat file."""
    text = Path(path).read_text()
    out = {}
    m = re.search(r"E I G E N V A L U E   O U T P U T(.*?)(?:P A R T I C I P|\Z)", text, re.S)
    if m:
        rows = [l.split() for l in m.group(1).splitlines()]
        rows = [r for r in rows if len(r) >= 5 and r[0].isdigit()]
        out["freq"] = np.array([float(r[3]) for r in rows])
    for key, title in (("participation", "P A R T I C I P A T I O N   F A C T O R S"),
                       ("eff_mass", "E F F E C T I V E   M O D A L   M A S S")):
        m = re.search(title + r"(.*?)(?:\n\s*\n\s*[A-Z] [A-Z]|\Z)", text, re.S)
        if m:
            rows = [l.split() for l in m.group(1).splitlines()]
            rows = [r for r in rows if len(r) == 7 and r[0].isdigit()]
            out[key] = np.array([[float(v) for v in r[1:]] for r in rows])
    m = re.search(r"T O T A L   E F F E C T I V E   M A S S(.*?)(?:\n\s*\n\s*[A-Z] [A-Z]|\Z)", text, re.S)
    if m:
        vals = re.findall(_FLOAT, m.group(1))
        out["total_eff_mass"] = np.array([float(v) for v in vals[-6:]])
    return out


def read_dat_mode_shapes(path: str | Path, set_name: str = "CG") -> dict:
    """Mode shape of a printed node set from the *FREQUENCY step: {mode number: (ux, uy, uz)}."""
    text = Path(path).read_text().splitlines()
    out, mode = {}, None
    for k, line in enumerate(text):
        if "E I G E N V A L U E    N U M B E R" in line:
            mode = int(line.split()[-1])
        elif mode is not None and line.strip().startswith("displacements") and f"set {set_name}" in line:
            j = k + 1
            while not text[j].strip():
                j += 1
            out[mode] = np.array([float(v) for v in text[j].split()[1:4]])
            mode = None
    return out


def read_dat_node_print(path: str | Path, set_name: str = "CG") -> list[np.ndarray]:
    """All '*NODE PRINT' displacement blocks for a node set, in file order."""
    text = Path(path).read_text().splitlines()
    out = []
    for k, line in enumerate(text):
        if line.strip().startswith("displacements") and f"set {set_name}" in line:
            j = k + 1
            while j < len(text) and not text[j].strip():
                j += 1
            vals = text[j].split()
            out.append(np.array([float(v) for v in vals[1:4]]))
    return out


def von_mises(s: np.ndarray) -> np.ndarray:
    """s: (..., 6) with components xx, yy, zz, xy, yz, zx (CalculiX order)."""
    sxx, syy, szz, sxy, syz, szx = (s[..., k] for k in range(6))
    return np.sqrt(0.5 * ((sxx - syy) ** 2 + (syy - szz) ** 2 + (szz - sxx) ** 2)
                   + 3.0 * (sxy ** 2 + syz ** 2 + szx ** 2))
